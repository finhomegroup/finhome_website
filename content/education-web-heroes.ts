//   (each made with a Pexels photo as composition reference only);
// - "supplement": per-article images generated by Codex,
//   artifacts/ai-web-heroes-2026-10-01/generated-supplement (prompt only, no
//   stock reference).
// The public files are plain sharp WebP resizes of the full 3:2 frame — no
// crop, no retouch, no upscale (1536 is the source width). Crops are CSS only:
// `focal` is the object-position for boxes wider than 3:2, and `mirror` flips
// the frame (no readable text in any of them).
//
// Not a photo by the reference's creator, not a customer, not an endorsement,
// and not a claim about any real place: image 09's lake has a small tower that
// resembles a real landmark; nothing on the page names or claims a location.

export const WEB_HERO_TAGLINE = "Ảnh minh họa AI";

export type WebHeroSource = { src: string; width: number; height: number };

export type EducationWebHero = {
  /**
   * "guide": a standalone tool guide's page hero and its thumbnails.
   * "article": a collection article's opening figure (after the short answer).
   */
  surface: "guide" | "collection" | "article";
  /** Post slug for a guide or article; the collection's own slug otherwise. */
  slug: string;
  /** Where the generated PNG lives in the local artifacts (see header). */
  origin: { set: "library"; n: number; file: string } | { set: "supplement"; id: string; file: string };
  /** SHA-256 of the generated PNG the WebP files were derived from. */
  generatedSha256: string;
  size: { w: number; h: number };
  /** 720 / 1200 / 1536 WebP, ascending. */
  sources: readonly [WebHeroSource, WebHeroSource, WebHeroSource];
  /** What is in frame only: no ethnicity, place, figure or relationship claim. */
  alt: string;
  /** CSS object-position for boxes wider than the 3:2 frame (keeps heads in). */
  focal: string;
  mirror: boolean;
  /**
   * The stock photo used ONLY as a composition reference — not the output's
   * author. `null` for supplement images, generated from a prompt alone.
   */
  compositionReference: { pexelsId: string; url: string; creator: string } | null;
  approvedOn: string;
};

const sources = (base: string) => {
  return [
    { src: `${base}-720.webp`, width: 720, height: 480 },
    { src: `${base}-1200.webp`, width: 1200, height: 800 },
    { src: `${base}-1536.webp`, width: 1536, height: 1024 },
  ] as const;
};

const hero = (
  surface: EducationWebHero["surface"],
  slug: string,
  n: number,
  name: string,
  generatedSha256: string,
  compositionReference: EducationWebHero["compositionReference"],
  alt: string,
  focal: string,
  mirror = false,
): EducationWebHero => ({
  surface,
  slug,
  origin: { set: "library", n, file: `images/${String(n).padStart(2, "0")}-${name}.png` },
  generatedSha256,
  size: { w: 1536, h: 1024 },
  sources: sources(`/images/education/ai-library-${String(n).padStart(2, "0")}-${name}`),
  alt: `${WEB_HERO_TAGLINE}: ${alt}`,
  focal,
  mirror,
  compositionReference,
  approvedOn: "2026-10-01",
});

const ref = (pexelsId: string, slug: string, creator: string) => ({
  pexelsId,
  url: `https://www.pexels.com/photo/${slug}-${pexelsId}/`,
  creator,
});

