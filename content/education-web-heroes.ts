/** A collection article's hero, if it has one (C05/C11 use their illustration). */
export function articleHero(slug: string): EducationWebHero | undefined {
  return ARTICLE_WEB_HEROES.find((h) => h.slug === slug);
}

/** The page hero of a standalone tool guide, if it has one. */
export function guideHero(slug: string): EducationWebHero | undefined {
  return EDUCATION_WEB_HEROES.find((h) => h.surface === "guide" && h.slug === slug);
}

export function collectionHero(): EducationWebHero {
  const h = EDUCATION_WEB_HEROES.find((x) => x.surface === "collection");
  if (!h) throw new Error("content/education-web-heroes.ts: no collection hero");
  return h;
}

export function webHeroSrcSet(h: EducationWebHero): string {
  return h.sources.map((s) => `${s.src} ${s.width}w`).join(", ");
}
